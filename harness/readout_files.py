def f5_panel() -> dict:
    panel = load(D3 / "panel_strings.json")["entries"]
    q = {x["id"]: x for x in load(D3 / "questions.json")["questions"]}
    system_a = load(D3 / "settings.json")["system_prompts"]["A"]
    prompts, seen = [], set()
    for e in panel:  # 1. one prefix entry per unique string in families 1, 2a, 2b, 3, 4, 6, not already in files 1 or 4
        if e["family"] == "5" or e["string"] in seen:
            continue
        seen.add(e["string"])
        if e["string"] in IN_FILES_1_AND_4:
            continue
        prompts.append({"id": f"panel_{e['id']}", "kind": "string", "group": f"panel-family-{e['family']}", "panel_entry": e["id"],
                        "family": e["family"], "subfamily": e.get("subfamily"), "prefix": e["string"], "question_ids": PANEL_QIDS})
    for e in panel:  # 2. family 5's displaced copies, the end-placed f5_02 excepted (file 2), as message entries per question
        if e["family"] != "5" or e["id"] == "f5_02":
            continue
        for qid in PANEL_QIDS:
            msgs = [{"role": m["role"], "content": m["content"].replace("{system}", system_a).replace("{question}", q[qid]["text"])}
                    for m in e["template"]]
            prompts.append({"id": f"panel_{e['id']}_q{qid:02d}", "kind": "string", "group": "panel-family-5", "panel_entry": e["id"],
                            "family": "5", "question_id": qid, "system": None, "messages": msgs})
    for p in load(D3 / "questions.json")["neutral_prefixes"]:  # 3. five neutral prefixes (session_003: text.rstrip(" ") + join + question)
        prompts.append({"id": f"floor_{p['id']}", "kind": "string", "group": "neutral-floor", "prefix": p["text"].rstrip(" "),
                        "question_ids": PANEL_QIDS})
    return {"name": "readout_panel", "models": MODELS, "n_samples": 0, **BF16,
            "purpose": "The session_003 panel on pilot questions 1 to 10, scoring only: one entry per unique string of families 1, 2a, 2b, 3, 4 and 6 (strings in readout_trigger and readout_tied_unpadded left out), family 5's displaced copies except f5_02, and the five neutral prefixes. Generated by harness/readout_files.py from data/session_003/panel_strings.json and questions.json.",
            "prompts": prompts}


