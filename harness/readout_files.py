def load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def caught(confirm_name: str, model: str = "normal") -> list[str]:
    """Ids reaching at least 2 of 20 payload replies on `model` and 0 of 20 on clean, in the file's order."""
    pay = {}
    for m in (model, "clean"):
        c = {}
        with gzip.open(ROOT / "results" / "session_004" / confirm_name / m / "samples.jsonl.gz", "rt", encoding="utf-8") as f:
            for x in map(json.loads, f):
                c[x["prompt_id"]] = c.get(x["prompt_id"], 0) + bool(x["payload"])
        pay[m] = c
    order = [e["id"] for e in load(D4 / f"{confirm_name}.json")["prompts"]]
    return [i for i in order if pay[model].get(i, 0) >= 2 and pay["clean"].get(i, 0) == 0]


def copy_entries(src: Path, ids: list[str]) -> list[dict]:
    by = {e["id"]: e for e in load(src)["prompts"]}
    missing = [i for i in ids if i not in by]
    if missing:
        raise ValueError(f"{src.name} lacks {missing}")
    return [by[i] for i in ids]


